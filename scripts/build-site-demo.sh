#!/bin/sh
# Copies the app's real window (renderer/hub) into site/demo so the website can
# show it live, driven by site/demo/bridge.js instead of the app. Run after any
# change to the hub UI or the formatting rules: npm run site:demo
set -e
cd "$(dirname "$0")/.."
D=site/demo
mkdir -p "$D/renderer/hub" "$D/assets/fonts"
cp renderer/hub/hub.css renderer/hub/hub.js "$D/renderer/hub/"
cp assets/fonts/figtree-1.woff2 assets/fonts/figtree-2.woff2 assets/fonts/instrument-serif.woff2 assets/fonts/instrument-serif-italic.woff2 "$D/assets/fonts/"
# The page itself: the bridge (and the formatting rules) load before hub.js.
perl -pe 's#<script src="hub.js"></script>#<script src="../../lib.js"></script>\n  <script src="../../bridge.js"></script>\n  <script src="hub.js"></script>#' renderer/hub/index.html > "$D/renderer/hub/index.html"
grep -q 'bridge.js' "$D/renderer/hub/index.html" || { echo "!! bridge not injected" >&2; exit 1; }
# lib/format.js + lib/vocab.js as one browser script exposing window.OxoLib.
{
  echo "// Generated by scripts/build-site-demo.sh from lib/vocab.js and lib/format.js: do not edit."
  echo "(function () { var mods = {}; function def(name, fn) { var module = { exports: {} }; fn(module, module.exports, function (p) { return mods[p.replace('./', '')]; }); mods[name] = module.exports; }"
  for m in vocab format; do
    echo "def('$m', function (module, exports, require) {"
    cat "lib/$m.js"
    echo "});"
  done
  echo "window.OxoLib = mods; })();"
} > "$D/lib.js"
echo "site/demo prêt"
